-- ========== Tables ==========
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'Writer',
  email text,
  bio text default '',
  role text not null default 'author' check (role in ('author','admin')),
  created_at timestamptz default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  description text default '',
  color text default '#6c4cff',
  created_at timestamptz default now()
);

create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text unique not null,
  excerpt text default '',
  content text default '',
  featured_image text default '',
  category_id bigint references public.categories(id) on delete set null,
  author_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  status text not null default 'draft' check (status in ('draft','pending','published')),
  tags text default '',
  meta_title text default '',
  meta_description text default '',
  views integer default 0,
  published_at timestamptz,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
create index if not exists articles_status_idx on public.articles(status, published_at desc);

create table if not exists public.settings (
  key text primary key,
  value text default ''
);

-- ========== Helpers ==========
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- New sign-up -> profile row (admin for the owner email)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id, name, email, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'name', ''), split_part(new.email, '@', 1)),
    new.email,
    case when lower(new.email) = 'arun.ahirwar.online@gmail.com' then 'admin' else 'author' end
  )
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Only admins may change roles / emails
create or replace function public.protect_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then
    new.role := old.role;
    new.email := old.email;
  end if;
  if new.id = auth.uid() and new.role <> old.role then
    new.role := old.role; -- nobody demotes/promotes themselves
  end if;
  return new;
end $$;
drop trigger if exists protect_profile on public.profiles;
create trigger protect_profile before update on public.profiles
  for each row execute function public.protect_profile();

-- Article rules: approval workflow, timestamps, ownership
create or replace function public.article_rules() returns trigger
language plpgsql security definer set search_path = public as $$
declare need_approval boolean;
begin
  select coalesce((select value from public.settings where key = 'require_approval'), '1') = '1' into need_approval;
  if tg_op = 'INSERT' then
    if not public.is_admin() then new.author_id := auth.uid(); end if;
    new.views := 0;
  else
    new.author_id := old.author_id;
    if not public.is_admin() then new.views := old.views; end if;
  end if;
  if not public.is_admin() and need_approval and new.status = 'published' then
    new.status := 'pending';
  end if;
  if new.status = 'published' and new.published_at is null then new.published_at := now(); end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists article_rules on public.articles;
create trigger article_rules before insert or update on public.articles
  for each row execute function public.article_rules();

-- Public view counter
create or replace function public.increment_views(p_slug text) returns void
language sql security definer set search_path = public as $$
  update public.articles set views = views + 1 where slug = p_slug and status = 'published';
$$;

-- Admin-only user list (includes email)
create or replace function public.admin_users()
returns table(id uuid, name text, email text, role text, created_at timestamptz, posts bigint)
language sql stable security definer set search_path = public as $$
  select p.id, p.name, p.email, p.role, p.created_at, count(a.id)
  from public.profiles p left join public.articles a on a.author_id = p.id
  where public.is_admin()
  group by p.id order by p.created_at desc;
$$;

-- Sitemap as XML (served through the REST API)
do $$ begin
  if not exists (select 1 from pg_type where typname = '*/*') then
    create domain "*/*" as text;
  end if;
end $$;
drop function if exists public.sitemap();
create function public.sitemap() returns "*/*"
language plpgsql stable security definer set search_path = public as $$
declare base text; xml text;
begin
  perform set_config('response.headers', '[{"Content-Type": "application/xml; charset=utf-8"}, {"Cache-Control": "public, max-age=3600"}]', true);
  select coalesce((select value from settings where key = 'site_url'), 'https://content-verse.surge.sh') into base;
  xml := '<?xml version="1.0" encoding="UTF-8"?>' || chr(10) ||
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' ||
    '<url><loc>' || base || '/</loc><changefreq>daily</changefreq></url>' ||
    coalesce((select string_agg('<url><loc>' || base || '/category/' || slug || '</loc></url>', '') from categories), '') ||
    coalesce((select string_agg('<url><loc>' || base || '/article/' || slug || '</loc><lastmod>' ||
      to_char(updated_at at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"') || '</lastmod></url>', '' order by published_at desc)
      from articles where status = 'published'), '') || '</urlset>';
  return xml;
end $$;

-- ========== Row Level Security ==========
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.articles enable row level security;
alter table public.settings enable row level security;

drop policy if exists "profiles readable" on public.profiles;
create policy "profiles readable" on public.profiles for select using (true);
drop policy if exists "profiles self update" on public.profiles;
create policy "profiles self update" on public.profiles for update using (id = auth.uid() or public.is_admin());
drop policy if exists "profiles admin delete" on public.profiles;
create policy "profiles admin delete" on public.profiles for delete using (public.is_admin() and id <> auth.uid());
-- table privileges (project has auto-grant disabled)
grant usage on schema public to anon, authenticated;
grant select on public.categories, public.articles, public.settings to anon, authenticated;
grant insert, update, delete on public.categories, public.articles, public.settings to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant delete on public.profiles to authenticated;
-- hide emails from the public
revoke select on public.profiles from anon, authenticated;
grant select (id, name, bio, role, created_at) on public.profiles to anon, authenticated;
grant update (name, bio, role) on public.profiles to authenticated;

drop policy if exists "categories readable" on public.categories;
create policy "categories readable" on public.categories for select using (true);
drop policy if exists "categories admin write" on public.categories;
create policy "categories admin write" on public.categories for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "articles read" on public.articles;
create policy "articles read" on public.articles for select
  using (status = 'published' or author_id = auth.uid() or public.is_admin());
drop policy if exists "articles insert" on public.articles;
create policy "articles insert" on public.articles for insert to authenticated with check (auth.uid() is not null);
drop policy if exists "articles update" on public.articles;
create policy "articles update" on public.articles for update using (author_id = auth.uid() or public.is_admin());
drop policy if exists "articles delete" on public.articles;
create policy "articles delete" on public.articles for delete using (author_id = auth.uid() or public.is_admin());

drop policy if exists "settings readable" on public.settings;
create policy "settings readable" on public.settings for select using (true);
drop policy if exists "settings admin write" on public.settings;
create policy "settings admin write" on public.settings for all using (public.is_admin()) with check (public.is_admin());

grant execute on function public.increment_views(text) to anon, authenticated;
grant execute on function public.sitemap() to anon, authenticated;
grant execute on function public.admin_users() to authenticated;

